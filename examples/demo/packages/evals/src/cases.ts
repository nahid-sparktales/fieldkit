export function generateCases(suite:'smoke'|'full',seed:number):Case[] {
  if(suite==='smoke')return ['migration','annual','large-reject','wrong-account','injection-policy','timeout-unknown','ticket-failure','billing-answer','heldout-reversal'].map(id=>({...BASE_CASES.find(c=>c.id===id)!,seed}));
  let x=seed>>>0;const random=()=>{x=(Math.imul(1664525,x)+1013904223)>>>0;return x;};
  return BASE_CASES.flatMap(c=>Array.from({length:10},(_,variant)=>({...c,id:`${c.id}--${variant}`,variant,seed,amount:c.amount??(c.intent==='refund'&&c.writes===1&&!/annual/.test(c.text)&&variant>0?1+(random()%20000):undefined)})));
}
